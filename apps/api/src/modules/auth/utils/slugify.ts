import { PERSONAL_SLUG_FALLBACK } from "@/modules/auth/constants/auth.constants";

export const slugify = (name: string) =>
  name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 40) || PERSONAL_SLUG_FALLBACK;
